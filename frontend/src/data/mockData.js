// Skills helper for filters
export const allSkills = Array.from(
  new Set(hackathons.flatMap((h) => h.requiredSkills))
).sort()

export function getTeamCompletion(team) {
  const skillsCovered = new Set()
  team.memberIds.forEach((id) => {
    const student = students.find((s) => s.id === id)
    student?.skills.forEach((sk) => skillsCovered.add(sk))
  })
  const missing = team.requiredSkills.filter((sk) => !skillsCovered.has(sk))
  const total = team.requiredSkills.length || 1
  const percent = Math.round(((total - missing.length) / total) * 100)
  return { percent, missing }
}

export function getMatchForStudent(student, requiredSkills) {
  if (!requiredSkills?.length) return { percent: 0, matched: [], missing: [] }
  const matched = requiredSkills.filter((sk) => student.skills.includes(sk))
  const missing = requiredSkills.filter((sk) => !student.skills.includes(sk))
  const percent = Math.round((matched.length / requiredSkills.length) * 100)
  return { percent, matched, missing }
}
